"""End-to-end smoke, one real conversion + verify per category (P1 gate).

All content is generated by the fixtures (lavfi + Pillow). HDR fixture is
real bt2020/PQ-tagged H.264 10-bit - probe must flag it as HDR (F15).
Document (LibreOffice) is marked slow: office startup dominates runtime.
"""
from __future__ import annotations

import pytest

from transmute.engines import engine_for

pytestmark = pytest.mark.e2e


def test_video_convert_verify(tmp_path, fixtures, need_ffmpeg):
    eng = engine_for("video")
    if not eng.availability().ok:
        pytest.skip("video engine unavailable")
    dst = tmp_path / "clip.mkv"
    res = eng.convert(fixtures["mp4"], dst, codec="av1")
    assert res.outcome in ("converted", "kept"), res.reason
    if res.outcome == "converted":
        assert dst.exists()
        v = eng.verify(fixtures["mp4"], dst)
        assert v.ok, v.reason


def test_audio_to_opus_and_flac(tmp_path, fixtures):
    eng = engine_for("audio")
    if not eng.availability().ok:
        pytest.skip("audio engine unavailable")
    for fmt in ("opus", "flac"):
        dst = tmp_path / f"tone.{fmt}"
        res = eng.convert(fixtures["mp3"], dst, codec=fmt)
        assert res.outcome == "converted", f"{fmt}: {res.reason}"
        assert dst.exists() and dst.stat().st_size > 0
        assert eng.verify(fixtures["mp3"], dst).ok, fmt


def test_image_jpg_to_webp_and_gif_stays_animated(tmp_path, fixtures):
    eng = engine_for("image")
    dst = tmp_path / "out.webp"
    res = eng.convert(fixtures["jpg"], dst, quality=75)
    assert res.outcome == "converted" and dst.exists()
    assert eng.verify(fixtures["jpg"], dst).ok
    gdst = tmp_path / "out.gif.webp"
    res2 = eng.convert(fixtures["gif"], gdst)
    assert res2.outcome in ("converted", "skipped"), res2.reason
    if res2.outcome == "converted":
        from PIL import Image
        im = Image.open(gdst)
        assert getattr(im, "n_frames", 1) > 1, "animated GIF must stay animated"


def test_pdf_lossless_engine_result_is_honest(tmp_path, fixtures):
    eng = engine_for("pdf")
    av = eng.availability()
    if not av.ok:
        pytest.skip("no pdf engine")
    dst = tmp_path / "out.pdf"
    res = eng.convert(fixtures["pdf"], dst)
    assert res.ok, res.reason  # converted|kept; failures must carry a reason
    if res.outcome == "converted":
        assert eng.verify(fixtures["pdf"], dst).ok
        from pikepdf import Pdf
        with Pdf.open(fixtures["pdf"]) as a, Pdf.open(dst) as b:
            assert len(a.pages) == len(b.pages)


